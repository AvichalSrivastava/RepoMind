// newPublisher creates a httptest-backed publisher with a per-test
// dispatch map: GET responses come from getResp, PUT calls invoke
// onPut. The handler synthesises Atlassian-shaped JSON.
func newPublisher(
	t *testing.T,
	maxRetries int,
	getBody func(call int32) string,
	onPut func(call int32, body []byte) (status int, resp string),
) (*confluence.Publisher, *int32, *int32) {
	t.Helper()
	var gets, puts int32
	mux := http.NewServeMux()
	mux.HandleFunc("/wiki/rest/api/content/", func(w http.ResponseWriter, r *http.Request) {
		switch r.Method {
		case http.MethodGet:
			n := atomic.AddInt32(&gets, 1)
			_, _ = w.Write([]byte(getBody(n)))
		case http.MethodPut:
			n := atomic.AddInt32(&puts, 1)
			body, _ := io.ReadAll(r.Body)
			status, resp := onPut(n, body)
			if status == 0 {
				status = http.StatusOK
			}
			w.WriteHeader(status)
			if resp != "" {
				_, _ = w.Write([]byte(resp))
			}
		default:
			w.WriteHeader(http.StatusMethodNotAllowed)
		}
	})
	srv := httptest.NewServer(mux)
	t.Cleanup(srv.Close)
	client, err := confluence.NewClient(confluence.Config{
		BaseURL:    srv.URL + "/wiki",
		Email:      "ops@example.com",
		APIToken:   "tok",
		Timeout:    2 * time.Second,
		MaxRetries: maxRetries,
	})
	require.NoError(t, err)
	return confluence.NewPublisher(client), &gets, &puts
}

func newNotes(t *testing.T, markdown string) *analysis.ReleaseNotes {
	t.Helper()
	entries := []analysis.ReleaseNoteEntry{{
		Category: analysis.CategoryFeature,
		Title:    "Add multi-team fan-out",
		PR:       shared.NewPullRequestID(),
	}}
	rn, err := analysis.NewReleaseNotes("Sprint 42 shipped.", markdown, entries)
	require.NoError(t, err)
	return &rn
}

func makeGetResponse(version int, body string) string {
	return fmt.Sprintf(`{
		"id":"42","type":"page","title":"Release Notes",
		"version":{"number":%d},
		"body":{"storage":{"value":%q,"representation":"storage"}},
		"_links":{"base":"https://acme.atlassian.net/wiki","webui":"/x/42"}
	}`, version, body)
}

func makePutResponse(newVersion int) string {
	return fmt.Sprintf(`{
		"id":"42","type":"page","title":"Release Notes",
		"version":{"number":%d},
		"body":{"storage":{"value":"<p>ignored</p>","representation":"storage"}},
		"_links":{"base":"https://acme.atlassian.net/wiki","webui":"/x/42"}
	}`, newVersion)
}

// ---------- happy path ----------

func TestPublish_FirstPublishAppendsSectionAndBumpsVersion(t *testing.T) {
	var putBody []byte
	publisher, gets, puts := newPublisher(t, 0,
		func(n int32) string { return makeGetResponse(5, "<p>existing</p>") },
		func(n int32, b []byte) (int, string) {
			putBody = b
			return http.StatusOK, makePutResponse(6)
		},
	)

	res, err := publisher.Publish(context.Background(), publish.Input{
		PageID:      "42",
		SectionName: "release-notes-MARV-42",
		Heading:     "Marvelous Sprint 42",
		Notes:       newNotes(t, "### Features\n- Add fan-out\n"),
		GeneratedAt: time.Date(2026, 6, 28, 12, 0, 0, 0, time.UTC),
	})
	require.NoError(t, err)
	assert.Equal(t, "42", res.PageID)
	assert.Equal(t, 6, res.NewVersion)
	assert.Equal(t, "https://acme.atlassian.net/wiki/x/42", res.URL)
	assert.EqualValues(t, 1, atomic.LoadInt32(gets))
	assert.EqualValues(t, 1, atomic.LoadInt32(puts))

	// PUT body must carry the new section markers and the rendered XHTML.
	var sent map[string]any
	require.NoError(t, json.Unmarshal(putBody, &sent))
	value := sent["body"].(map[string]any)["storage"].(map[string]any)["value"].(string)
	assert.Contains(t, value, "<p>existing</p>", "preamble is preserved")
	assert.Contains(t, value, `<!-- repomind:section:start name="release-notes-MARV-42" -->`)
	assert.Contains(t, value, "<h2>Marvelous Sprint 42</h2>")
	assert.Contains(t, value, "<p>Sprint 42 shipped.</p>")
	assert.Contains(t, value, "<h3>Features</h3>")
	assert.Contains(t, value, "<li>Add fan-out</li>")
	assert.Contains(t, value, "Generated by RepoMind at 2026-06-28T12:00:00Z")
	assert.Contains(t, value, `<!-- repomind:section:end name="release-notes-MARV-42" -->`)

	// Version sent = current + 1.
	require.Equal(t, float64(6), sent["version"].(map[string]any)["number"])
}

func TestPublish_SecondPublishReplacesExistingSection(t *testing.T) {
	existing := `<p>preamble</p>` +
		`<!-- repomind:section:start name="rn-1" --><h2>OLD</h2><!-- repomind:section:end name="rn-1" -->` +
		`<p>postscript</p>`
	var putBody []byte
	publisher, _, _ := newPublisher(t, 0,
		func(n int32) string { return makeGetResponse(11, existing) },
		func(n int32, b []byte) (int, string) {
			putBody = b
			return http.StatusOK, makePutResponse(12)
		},
	)

	_, err := publisher.Publish(context.Background(), publish.Input{
		PageID:      "42",
		SectionName: "rn-1",
		Heading:     "Sprint 43",
		Notes:       newNotes(t, "### Features\n- Brand new\n"),
	})
	require.NoError(t, err)

	var sent map[string]any
	require.NoError(t, json.Unmarshal(putBody, &sent))
	value := sent["body"].(map[string]any)["storage"].(map[string]any)["value"].(string)
	assert.Contains(t, value, "<p>preamble</p>")
	assert.Contains(t, value, "<p>postscript</p>")
	assert.Contains(t, value, "<h2>Sprint 43</h2>")
	assert.NotContains(t, value, "<h2>OLD</h2>", "old section body must be replaced")
}

// ---------- 409 retry ----------

func TestPublish_RetriesOn409Conflict(t *testing.T) {
	// First GET returns version 1, first PUT fails with 409 (someone
	// else bumped the page to v2). Second GET returns version 2, second
	// PUT succeeds.
	getVersions := []int{1, 2}
	publisher, gets, puts := newPublisher(t, 2,
		func(n int32) string { return makeGetResponse(getVersions[n-1], "<p>x</p>") },
		func(n int32, b []byte) (int, string) {
			if n == 1 {
				return http.StatusConflict, ""
			}
			return http.StatusOK, makePutResponse(3)
		},
	)
	res, err := publisher.Publish(context.Background(), publish.Input{
		PageID:      "42",
		SectionName: "rn-1",
		Heading:     "Sprint 43",
		Notes:       newNotes(t, "### F\n- x\n"),
	})
	require.NoError(t, err)
	assert.Equal(t, 3, res.NewVersion)
	assert.EqualValues(t, 2, atomic.LoadInt32(gets), "publisher must re-fetch after 409")
	assert.EqualValues(t, 2, atomic.LoadInt32(puts))
}

func TestPublish_ExhaustsConflictRetriesAndReturnsConflict(t *testing.T) {
	publisher, _, puts := newPublisher(t, 1,
		func(n int32) string { return makeGetResponse(1, "<p>x</p>") },
		func(n int32, b []byte) (int, string) { return http.StatusConflict, "" },
	)
	_, err := publisher.Publish(context.Background(), publish.Input{
		PageID: "42", SectionName: "rn", Heading: "H",
		Notes: newNotes(t, "### F\n- x\n"),
	})
	require.ErrorIs(t, err, publish.ErrConflict)
	assert.EqualValues(t, 2, atomic.LoadInt32(puts), "should PUT MaxRetries+1 times")
}


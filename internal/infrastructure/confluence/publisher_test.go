func TestPublish_NotFoundOnGetSurfacesAsPublishErrNotFound(t *testing.T) {
	// Force the GET to 404 by overriding via a fresh client.
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusNotFound)
	}))
	t.Cleanup(srv.Close)
	client, _ := confluence.NewClient(confluence.Config{
		BaseURL: srv.URL + "/wiki", Email: "e", APIToken: "t",
	})
	publisher := confluence.NewPublisher(client)
	_, err := publisher.Publish(context.Background(), publish.Input{
		PageID: "42", SectionName: "rn", Heading: "H",
		Notes: newNotes(t, "### F\n- x\n"),
	})
	require.ErrorIs(t, err, publish.ErrNotFound)
}


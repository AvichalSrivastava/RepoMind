func TestPublish_DuplicateMarkersSurfaceAsInvalidPage(t *testing.T) {
	bad := `<!-- repomind:section:start name="rn" -->a<!-- repomind:section:end name="rn" -->` +
		`<!-- repomind:section:start name="rn" -->b<!-- repomind:section:end name="rn" -->`
	publisher, _, _ := newPublisher(t, 0,
		func(n int32) string { return makeGetResponse(1, bad) },
		func(n int32, b []byte) (int, string) { t.Fatal("PUT should not happen"); return 0, "" },
	)
	_, err := publisher.Publish(context.Background(), publish.Input{
		PageID: "42", SectionName: "rn", Heading: "H",
		Notes: newNotes(t, "### F\n- x\n"),
	})
	require.ErrorIs(t, err, publish.ErrInvalidPage)
}

// ---------- input validation ----------

func TestPublish_ValidatesInput(t *testing.T) {
	publisher, _, _ := newPublisher(t, 0,
		func(n int32) string { t.Fatal("GET should not happen"); return "" },
		func(n int32, b []byte) (int, string) { t.Fatal("PUT should not happen"); return 0, "" },
	)
	notes := newNotes(t, "### F\n- x\n")

	cases := []struct {
		name string
		in   publish.Input
	}{
		{"empty page id", publish.Input{SectionName: "rn", Heading: "H", Notes: notes}},
		{"invalid section name (space)", publish.Input{PageID: "1", SectionName: "has space", Heading: "H", Notes: notes}},
		{"invalid section name (quote)", publish.Input{PageID: "1", SectionName: `q"q`, Heading: "H", Notes: notes}},
		{"empty heading", publish.Input{PageID: "1", SectionName: "rn", Heading: "  ", Notes: notes}},
		{"nil notes", publish.Input{PageID: "1", SectionName: "rn", Heading: "H", Notes: nil}},
	}
	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			_, err := publisher.Publish(context.Background(), tc.in)
			require.Error(t, err)
		})
	}
}


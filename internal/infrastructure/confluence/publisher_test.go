// TestPublish_UnlinkedPRsSectionRendered verifies that a non-empty
// UnlinkedPRs slice produces a section wrapped in the fixed
// "unlinked-prs-table" markers, with the PR # rendered as a link and
// the head branch surfaced verbatim (this is exactly the signal the
// operator uses to trace the miss back to the developer).
func TestPublish_UnlinkedPRsSectionRendered(t *testing.T) {
	var putBody []byte
	publisher, _, puts := newPublisher(t, 0,
		func(n int32) string { return makeGetResponse(1, "<p>preamble</p>") },
		func(n int32, b []byte) (int, string) {
			putBody = b
			return http.StatusOK, makePutResponse(2)
		},
	)

	_, err := publisher.Publish(context.Background(), publish.Input{
		PageID:      "42",
		SectionName: "release-notes-x",
		Heading:     "Sprint 42",
		Notes:       newNotes(t, "### F\n- x\n"),
		UnlinkedPRs: []publish.UnlinkedPRRef{
			{
				RepoFullName: "acme/api",
				Number:       913,
				Title:        "hotfix: bump timeout",
				Author:       "alice",
				HeadBranch:   "hotfix/timeout",
				MergedAt:     time.Date(2026, 6, 28, 15, 4, 0, 0, time.UTC),
				URL:          "https://github.com/acme/api/pull/913",
			},
		},
	})
	require.NoError(t, err)
	assert.EqualValues(t, 1, atomic.LoadInt32(puts))

	var sent map[string]any
	require.NoError(t, json.Unmarshal(putBody, &sent))
	value := sent["body"].(map[string]any)["storage"].(map[string]any)["value"].(string)
	assert.Contains(t, value, `<!-- repomind:section:start name="unlinked-prs-table" -->`)
	assert.Contains(t, value, `<!-- repomind:section:end name="unlinked-prs-table" -->`)
	assert.Contains(t, value, "hotfix/timeout", "head branch is the diagnostic signal")
	assert.Contains(t, value, "https://github.com/acme/api/pull/913")
	assert.Contains(t, value, "alice")
}

// TestPublish_UnlinkedPRsSectionClearedWhenEmpty verifies that an
// empty UnlinkedPRs slice clears a stale section on the page. This
// is the "orphan later got attributed" case: previous publish left a
// row, this publish must remove it.
func TestPublish_UnlinkedPRsSectionClearedWhenEmpty(t *testing.T) {
	existing := `<p>preamble</p>` +
		`<!-- repomind:section:start name="unlinked-prs-table" -->` +
		`<table><tr><td>acme/api #913</td></tr></table>` +
		`<!-- repomind:section:end name="unlinked-prs-table" -->` +
		`<p>postscript</p>`
	var putBody []byte
	publisher, _, puts := newPublisher(t, 0,
		func(n int32) string { return makeGetResponse(3, existing) },
		func(n int32, b []byte) (int, string) {
			putBody = b
			return http.StatusOK, makePutResponse(4)
		},
	)

	_, err := publisher.Publish(context.Background(), publish.Input{
		PageID:      "42",
		SectionName: "release-notes-x",
		Heading:     "Sprint 42",
		Notes:       newNotes(t, "### F\n- x\n"),
		// UnlinkedPRs deliberately empty.
	})
	require.NoError(t, err)
	assert.EqualValues(t, 1, atomic.LoadInt32(puts))

	var sent map[string]any
	require.NoError(t, json.Unmarshal(putBody, &sent))
	value := sent["body"].(map[string]any)["storage"].(map[string]any)["value"].(string)
	assert.Contains(t, value, "<p>preamble</p>")
	assert.Contains(t, value, "<p>postscript</p>")
	assert.NotContains(t, value, "acme/api #913", "stale unlinked row must be cleared")
	// Markers themselves may remain (empty body between them); the
	// UX guarantee is that no visible orphan row is shown -- the next
	// publish with orphans will re-populate the section cleanly.
}

